COL = r'(?:столбц\w*|столбе\w*|колонк\w*|кол\.?|графе|графы|графа)\s+([A-Za-zА-Яа-я]{1,2})\b'
SPLIT = re.compile(r'\b(где|если|когда|у которых|в которых|при условии|по условию|для которых|которые)\b')
COMPARE = [(r'больше или равно|не меньше', '>='), (r'меньше или равно|не больше', '<='),
           (r'больше|свыше|более', '>'), (r'меньше|менее|ниже', '<'), (r'не равно|кроме', '<>')]


def _col(letter):
    return letter.upper().translate(CYR_TO_LAT)


def _columns(text):
    return [_col(m.group(1)) for m in re.finditer(COL, text, re.IGNORECASE)] + \
           [_col(m.group(1)) for m in re.finditer(r'\b(?:в|из|по)\s+([A-Za-z])\b', text)]


def _criterion(text):
    """('"Москва"' or '">100"', raw value) from the condition part of the request."""
    q = re.search(r'[«"„“]([^»"”]+)[»"”]', text)
    op = ''
    for words, sign in COMPARE:
        if re.search(words, text, re.IGNORECASE):
            op = sign
            break
    if q:
        value = q.group(1)
    else:
        m = re.search(r'(?:равн\w*|=|стоит|указан\w*|записан\w*|написан\w*|больше|меньше|свыше|более|менее|кроме|не равно)\s+(?:чем\s+)?(-?\d+(?:[.,]\d+)?|[А-Яа-яЁёA-Za-z][\wё-]*)', text, re.IGNORECASE)
        if not m:
            return None, None
        value = m.group(1)
    is_number = re.fullmatch(r'-?\d+(?:[.,]\d+)?', value) is not None
    value = value.replace('.', ',') if is_number else value
    if op:
        return f'"{op}{value}"', (op, value if is_number else f'"{value}"')
    return (value if is_number else f'"{value}"'), ('=', value if is_number else f'"{value}"')


def build_formula(request):
    """Returns (formula, explanation) or (None, hint). Fills in columns and condition from the request."""
    q = request.lower().replace('ё', 'е')
    for words, template, note in TEMPLATES:
        # COND — в запросе есть условие: «где», «если», «у которых»…
        if not all((SPLIT.search(q) is not None) if w == 'COND' else (w in q) for w in words):
            continue
        parts = SPLIT.split(request, maxsplit=1)
        left = parts[0]
        right = ''.join(parts[2:]) if len(parts) > 2 else ''
        value_cols = _columns(left) or ['A']
        cond_cols = _columns(right) or (value_cols[1:2] if len(value_cols) > 1 else [])
        crit, compare = _criterion(right or request)
        assumed = []
        v = value_cols[0]
        c = cond_cols[0] if cond_cols else ('A' if v != 'A' else 'B')
        if '{c}' in template and not cond_cols:
            assumed.append(f'условие проверяется в столбце {c}')
        k = crit or '"значение"'
        if crit is None and ('{k}' in template or '{kv}' in template):
            assumed.append('условие не поняла — замените "значение"')
        filled = template.format(v=f'{v}:{v}', c=f'{c}:{c}', k=k, c2='C:C', k2='"значение2"',
                                 t='E2', c1=f'{v}2', op=compare[0] if compare else '>', kv=compare[1] if compare else '0')
        explanation = note
        if assumed:
            explanation += ' Предположила: ' + '; '.join(assumed) + '.'
        return filled, explanation + ' Разделитель — точка с запятой (русский Excel).'
    return None, ('Не поняла задачу. Примеры: «сумма столбца C где в столбце A "Москва"», «количество где в B больше 100», '
                  '«подтянуть с другого листа», «рабочие дни между датами», «стаж», «найти повторы в столбце A».')


def explain_formula(formula):
    """Explains each function in a formula in plain Russian."""
    names = []
    for name in re.findall(r'([А-ЯЁA-Z][А-ЯЁA-Z.0-9]*)\s*\(', formula.upper()):
        if name not in names:
            names.append(name)
    if not names:
        return 'В формуле нет функций — это вычисление или ссылка на ячейки.'
    lines = []
    for n in names:
        lines.append(f'• {n} — {FUNCTIONS.get(n, "функция не из моего справочника")}')
    if ';' not in formula and ',' in formula:
        lines.append('Внимание: в русском Excel аргументы разделяются «;», а не «,».')
    return '\n'.join(lines)
