class AllMacros(unittest.TestCase):
    def test_every_action_compiles_clean(self):
        seen = set()
        for app, tasks in (('excel', EXCEL), ('word', WORD), (None, [e.split(': ', 1)[1] for e in v.EXAMPLES])):
            for t in tasks:
                code, steps, unknown = v.generate(t, app)
                self.assertEqual(unknown, [], t)
                self.assertEqual(v.lint(code), [], t)
                seen |= {s.op.key for s in steps}
        self.assertEqual(seen, {o.key for o in v.OPS})             # проверено каждое действие

    def test_checker_catches_typical_mistakes(self):
        bad = '\n'.join([
            'Option Explicit', 'Sub A()', '    Dim i As Long', '    Dim i As Long', '    On Error GoTo Oops',
            '    MsgBox "не закрыта', '    ActiveDocument.Range.Text = ""', '    Call B(1, 2)', '    Exit Function', 'End Sub',
            'Sub B(x As Long)', '    ActiveSheet.Range("A1").Value = x', '    Worksheets(1).Activate', 'End Sub'])
        text = ' '.join(m for _, m in v.lint(bad))
        for expected in ('дважды', 'GoTo', 'кавычка', 'только в Word', 'аргументами', 'Exit Function'):
            self.assertIn(expected, text)


