if __name__ == '__main__':
    ai.BASE = sys.argv[1]
    import tempfile
    from pathlib import Path
    samples = Path(tempfile.mkdtemp())
    (samples / 'Телеграмма о проверке техники.txt').write_text(SAMPLE, encoding='utf-8')
    ai.STYLE_DIR = samples                                  # образец отдела — как у пользователя в папке «образцы»
    binary, model = ai.local_files()
    if not binary.is_file() or model is None:
        sys.exit(f'Нет движка или модели в {ai.BASE}')
    print(f'Модель: {model.name}, движок: {binary.name}\n', flush=True)
    total = time.time()
    for name, job in TASKS:
        t = time.time()
        try:
            out = job()
            text = out if isinstance(out, str) else ' | '.join(str(x) for x in out if isinstance(x, (str,)))
            if isinstance(out, tuple) and len(out) == 2 and isinstance(out[1], str) and out[0] in ai.COMMANDS:
                text = f'команда={out[0]}, что={out[1]}'
        except ai.AIError as exc:
            text = f'ОШИБКА: {exc}'
        print(f'===== {name} ({time.time() - t:.1f} с)\n{text}\n', flush=True)
    print(f'Всего: {time.time() - total:.0f} с')
