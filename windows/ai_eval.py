"""Проверка качества локальной нейросети на типовых задачах (запускается в сборке, печатает ответы и время).
python ai_eval.py <папка, где лежат engine и models>"""
import sys
import time

import iskra_ai as ai

TG = ('тлг 154.docx', 'ТЕЛЕГРАММА\nОт кого: Штаб округа\nНомер: 154/2\nДата: 20.10.2026\nТекст:\n'
      'В целях проверки готовности подразделений:\n1. Представить сведения о численности личного состава до 25.10.2026.\n'
      '2. Обеспечить готовность техники к 27.10.2026.\nПодпись: Начальник штаба полковник И.И. Иванов')
SVOD = ('свод.xlsx', 'Наименование | По списку | На лицо\nГоспиталь | 120 | 115\nПолигон | 80 | 78\nМодуль 1 | 42 | 40\nИтого | 242 | 233')
PRIKAZ = ('приказ 7.docx', 'ПРИКАЗ № 7 от 15.10.2026\nО проверке готовности техники.\n'
          'Начальникам подразделений до 26.10.2026 провести осмотр техники и доложить о результатах.')

TASKS = [
    ('Ответ по документу', lambda: ai.answer('Какой срок представления сведений о численности?', [TG])),
    ('Ответ: нет в документах', lambda: ai.answer('Кто назначен ответственным за проверку?', [TG])),
    ('Телеграмма-ответ', lambda: ai.write('Составь телеграмму-ответ на телеграмму 154/2: сведения о численности '
                                          'направляем, техника готова', [TG, SVOD])),
    ('Доклад по своду', lambda: ai.write('Подготовь доклад начальнику о численности личного состава по своду', [SVOD])),
    ('Справка по приказу', lambda: ai.write('Напиши справку о выполнении приказа № 7', [PRIKAZ])),
    ('Официальный стиль', lambda: ai.edit('Ребята, до пятницы скиньте инфу сколько у вас людей и какая техника на ходу. '
                                          'Не тяните, начальство ругается.', 'Официальный стиль')),
    ('Исправить ошибки', lambda: ai.edit('Согласно приказа № 7 прошу в течении трех дней предоставить отчет о '
                                         'проведенной проверки.', 'Исправить ошибки')),
    ('Формула СУММЕСЛИ', lambda: ai.formula('сумма значений столбца C, где в столбце A написано Госпиталь')),
    ('Формула СЧЁТЕСЛИ', lambda: ai.formula('сколько строк, где в столбце D стоит «просрочено»')),
    ('Формула ВПР', lambda: ai.formula('подтянуть численность из листа Свод по названию организации из A2 (численность во 2-м столбце)')),
    ('Обобщение папки', lambda: ai.summarize('Обзор папки Телеграммы', TG[1] + '\n\n' + PRIKAZ[1] + '\n\n' + SVOD[1])),
]

if __name__ == '__main__':
    base = sys.argv[1]
    binary, model = ai.local_files(base)
    print(f'Модель: {model.name}, движок: {binary.name}\n', flush=True)
    total = time.time()
    for name, job in TASKS:
        t = time.time()
        try:
            out = job()
            text = out if isinstance(out, str) else ' | '.join(str(x) for x in out if isinstance(x, str))
        except ai.AIError as exc:
            text = f'ОШИБКА: {exc}'
        print(f'===== {name} ({time.time() - t:.1f} с)\n{text}\n', flush=True)
    print(f'Всего: {time.time() - total:.0f} с')
