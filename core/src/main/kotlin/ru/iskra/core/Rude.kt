package ru.iskra.core

import kotlin.random.Random

/**
 * Режим «с матом» (18+), включается только по желанию пользователя.
 * Искра матерится для красного словца и огрызается в ответ, но без оскорблений
 * по национальности, полу и прочему — просто дерзкая подруга.
 */
object Rude {
    // Корень с начала слова, допускаем приставки: «нахуй», «отъебись», «распиздяй».
    private val SWEAR = Regex(
        "(?<![а-я])(?:на|по|до|за|ни|от|о|у|вы|рас|рос|под|отъ|подъ|съ|въ|разъ|объ)?" +
            "(ху[йяеёию]|пизд|п[иі]зж|[её]б[аеиоуы]|[её]бл|бля|сук[аио]|мудак|мудил|залуп|говн|дерьм|жоп)",
    )

    fun hasSwearing(text: String) = SWEAR.containsMatchIn(normalize(text).replace('ё', 'е').let { " $it" })

    private val OPENERS = listOf(
        "Бля, ", "Ёпта, ", "Короче, ", "Слушай сюда: ", "Ну охуеть теперь, ", "Так, блять, ", "Ебать, ",
    )

    private val CLOSERS = listOf(
        " Вот так, нахуй.", " Пиздец, да?", " Охуенно же.", " Не благодари, блять.", " Всё, ебать.",
    )

    private val COMEBACKS = listOf(
        "Ты чё, охуел? Я тут, между прочим, стараюсь.",
        "Ой, блять, напугал. Говори, что надо, а то нахуй пойду спать.",
        "Сам такой, нахуй. Ладно, чем помочь?",
        "Ебать ты грозный. Давай по делу.",
        "Полегче на поворотах, сука, я тебе напоминания ставлю.",
        "Пиздеть — не мешки ворочать. Задачу давай.",
    )

    val MOOD = listOf(
        "Да заебись всё! Чем помочь?",
        "Нормас, бля. Сам как?",
        "Охуенно! Готова к делам, давай.",
    )

    val JOKES = listOf(
        "Идёт мужик по пустыне, видит — лампа. Потёр, вылез джинн: «Три желания». Мужик: «Хочу, чтобы всё было заебись». Джинн: «Бля, ну ты задал. Две оставшиеся сгорают».",
        "Будильник — единственная хуйня в доме, которая орёт на тебя по расписанию и ещё гордится этим.",
        "Купил умную колонку. Спросил, как жить. Она сказала: «Не знаю, бля, я колонка». Честнее, чем половина людей.",
        "Понедельник — это когда ты ещё не проснулся, а уже заебался.",
    )

    const val ON = "Ну наконец-то, блять! Теперь буду говорить как есть. Выключить — скажи «без мата»."
    const val OFF = "Ладно, ладно, без мата. Буду вежливой, как бабушка на кассе."
    const val HINT = "Эй, полегче! Хочешь, чтобы я тоже материлась, — скажи «включи мат»."

    private val LEADING = Regex("^((бля\\S*|блин|сука|ебать|епта|ептыть|нахуй|пиздец|охуеть|короче)[,!.\\s]+)+", RegexOption.IGNORE_CASE)
    private val AT_ME = Regex("(^| )(иди на|иди в|пошла|пошел|отъебись|отвали|заткнись|тупая|тупица|дура|овца)|ты (сука|бля|ебан|охуел|тупая|дура|долбо)")

    /** «Бля, поставь будильник» → «поставь будильник»: крепкое словцо в начале не мешает команде. */
    fun stripLeading(text: String) = text.trim().replace(LEADING, "").trim()

    /** Ругань в адрес Искры, а не просьба с крепким словцом. */
    fun isInsult(text: String): Boolean {
        val t = normalize(text)
        return hasSwearing(t) && (AT_ME.containsMatchIn(t) || stripLeading(t).isEmpty())
    }

    fun comeback(random: Random = Random.Default) = COMEBACKS.random(random)

    /** Добавляет к ответу крепкое словцо, если его там ещё нет. */
    fun spice(text: String, random: Random = Random.Default): String {
        if (text.isBlank() || hasSwearing(text)) return text
        return when (random.nextInt(3)) {
            0 -> OPENERS.random(random) + text.replaceFirstChar { it.lowercase() }
            1 -> text.trimEnd() + CLOSERS.random(random)
            else -> text
        }
    }
}
